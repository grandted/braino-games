export const PI_DIGITS: readonly string[] = [...DIGITS]

/** How many digits are available before the mode would run dry. */
export const PI_DIGIT_COUNT = PI_DIGITS.length

/**
 * The digits entered so far, written the way a person would: `3.14159`.
 * Used by the HUD readout during a Pi run.
 */
export function formatPi(count: number): string {
  if (count <= 0) return ''
  if (count === 1) return DIGITS[0]
  return `${DIGITS[0]}.${DIGITS.slice(1, count)}`
}
